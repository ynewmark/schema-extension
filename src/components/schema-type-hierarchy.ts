export function getOptionTypeNames(option: SchemaTypeOption): string[] {
    return [
        ...(option.type ? [option.type] : []),
        ...(option.children?.flatMap(getOptionTypeNames) ?? []),
    ];
}

function getTypeMatches(options: SchemaTypeOption[]): Map<string, string[]> {
    const matches = new Map<string, string[]>();
    function addMatches(type: string, types: string[]) {
        matches.set(type, [...new Set([...(matches.get(type) ?? []), ...types])]);
    }

    for (const option of options) {
        if (option.type) {
            addMatches(option.type, getOptionTypeNames(option));
        }
        if (option.children) {
            for (const [type, types] of getTypeMatches(option.children)) {
                addMatches(type, types);
            }
        }
    }
    return matches;
}

